async (page) => {
  const failures = [];
  const checks = [];
  const check = (condition, label) => { if (!condition) failures.push(label); else checks.push(label); };
  const errors = [];
  page.on('pageerror', error => errors.push(error.message));
  await page.addInitScript(() => {
    window.__munchyCLS = 0;
    new PerformanceObserver(list => { for (const entry of list.getEntries()) if (!entry.hadRecentInput) window.__munchyCLS += entry.value; }).observe({ type: 'layout-shift', buffered: true });
  });
  await page.goto('http://localhost:3000/');
  await page.evaluate(() => { localStorage.removeItem('munchy-cart'); localStorage.setItem('munchy_locale', 'en'); document.cookie = 'munchy_locale=en; Path=/; SameSite=Lax'; });
  const metrics = [];
  for (const width of [375, 768, 1440]) {
    await page.setViewportSize({ width, height: width === 375 ? 812 : 1000 });
    await page.goto('http://localhost:3000/');
    await page.evaluate(() => document.fonts.ready);
    await page.waitForTimeout(1000);
    const dimensions = await page.evaluate(() => ({ width: innerWidth, scroll: document.documentElement.scrollWidth, cls: window.__munchyCLS }));
    metrics.push({ viewport: width, ...dimensions });
    check(dimensions.scroll <= dimensions.width + 1, `Home has no horizontal overflow at ${width}px`);
    await page.screenshot({ path: `output/playwright/home-${width}.png` });
    await page.getByRole('button', { name: 'Reserve a table', exact: true }).first().click();
    check(await page.getByRole('dialog').isVisible(), `Reservation opens at ${width}px`);
    await page.keyboard.press('Escape');
    await page.waitForTimeout(350);
    check(await page.getByRole('dialog').count() === 0, `Escape closes modal at ${width}px`);
  }
  await page.setViewportSize({ width: 375, height: 812 });
  await page.getByRole('button', { name: 'AR', exact: true }).click();
  await page.waitForTimeout(1400);
  check(await page.locator('html').getAttribute('dir') === 'rtl', 'Arabic switches direction without reload');
  check(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth + 1), 'Arabic home has no mobile overflow');
  await page.screenshot({ path: 'output/playwright/home-arabic-375.png' });
  await page.reload();
  check(await page.locator('html').getAttribute('dir') === 'rtl', 'Arabic persists across navigation');
  await page.getByRole('button', { name: 'EN', exact: true }).click();
  await page.goto('http://localhost:3000/menu');
  const search = page.getByRole('textbox', { name: 'Search burgers, tacos, sides…' });
  await search.fill('burgr');
  check(await page.locator('.catalog-card').count() > 0, 'Fuzzy search finds burger after typo');
  await search.fill('zzzznomatch');
  check(await page.locator('.recommended-empty button').count() > 0, 'Empty search offers real menu suggestions');
  await search.fill('');
  await page.getByRole('button', { name: 'Quick look: The Double Trouble', exact: true }).click();
  const dialog = page.getByRole('dialog');
  await dialog.getByRole('radio', { name: 'Cola · 33cl +12 DH', exact: true }).check();
  await dialog.getByRole('button', { name: 'More drink', exact: true }).click();
  await dialog.getByRole('textbox', { name: 'Kitchen notes', exact: true }).fill('No raw onion please');
  await dialog.getByRole('radio', { name: 'Mild', exact: true }).check();
  await dialog.getByRole('button', { name: 'Add to bag 79 DH', exact: true }).click();
  check(await dialog.getByRole('button', { name: 'Added to your bag 79 DH', exact: true }).isVisible(), 'Customizer totals two drinks and gives add feedback');
  await page.keyboard.press('Escape');
  await page.getByRole('button', { name: 'Your bag 1', exact: true }).click();
  check((await page.getByRole('dialog').innerText()).includes('No raw onion please'), 'Kitchen notes persist into cart');
  await page.screenshot({ path: 'output/playwright/cart-375.png' });
  await page.keyboard.press('Escape');
  await page.goto('http://localhost:3000/checkout');
  await page.locator('.checkout-submit').waitFor({ state: 'visible' });
  check(await page.locator('.checkout-submit').isVisible(), 'Checkout accepts configured cart');
  await page.screenshot({ path: 'output/playwright/checkout-375.png' });
  await page.emulateMedia({ reducedMotion: 'reduce' });
  await page.goto('http://localhost:3000/');
  check(await page.evaluate(() => !document.documentElement.classList.contains('lenis')), 'Reduced motion bypasses Lenis');
  check(await page.evaluate(() => getComputedStyle(document.querySelector('.signature-sticky')).position) !== 'sticky', 'Reduced motion uses native gallery');
  await page.emulateMedia({ reducedMotion: 'no-preference' });
  check(errors.length === 0, 'No JavaScript runtime errors');
  if (failures.length) throw new Error(JSON.stringify({ checks, metrics, errors, failures }));
  return { checks, metrics, errors, failures };
}
